import Foundation

@main
struct ModelsTest {
    static func main() throws {
        let decoder = JSONDecoder()
        let activeOld = try decoder.decode(Session.self, from: Data(#"{"id":"ses_old","title":"Old but active","location":{"directory":"/workspace"},"time":{"created":1,"updated":900,"viewed":1}}"#.utf8))
        let newQuiet = try decoder.decode(Session.self, from: Data(#"{"id":"ses_new","title":"New but quiet","location":{"directory":"/workspace"},"time":{"created":500,"updated":500,"viewed":9999}}"#.utf8))
        let tie = try decoder.decode(Session.self, from: Data(#"{"id":"ses_z","location":{"directory":"/workspace"},"time":{"created":0,"updated":900}}"#.utf8))
        precondition(SessionActivityOrder.sorted([newQuiet, activeOld, tie]).map(\.id) == ["ses_z", "ses_old", "ses_new"])
        let refreshedOld = try decoder.decode(Session.self, from: Data(#"{"id":"ses_old","title":"Fresh metadata","location":{"directory":"/workspace"},"time":{"created":1,"updated":1000}}"#.utf8))
        let mergedSessions = SessionActivityOrder.merge(existing: [newQuiet, activeOld, tie], incoming: [refreshedOld, newQuiet])
        precondition(mergedSessions.count == 3 && mergedSessions.first?.id == "ses_old" && mergedSessions.first?.title == "Fresh metadata")
        print("PASS: server activity order ignores creation/viewed, matches ID tie-break and replaces stale paginated metadata")
        precondition(MessageBlock.parse("```swift\nprint(1)\n```") == [.code("swift", "print(1)")])
        precondition(MessageBlock.parse("```\nunfinished") == [.code("", "unfinished")])
        precondition(MessageBlock.parse("| A | B |\n| --- | --- |\n| 1 | 2 |") == [.table([["A", "B"], ["1", "2"]])])
        precondition(MessageBlock.parse("ordinary | text") == [.prose("ordinary | text")])
        precondition(MessageBlock.parse("|\n|") == [.prose("|\n|")])
        print("PASS: fenced code, incomplete streaming code, tables and prose parsing")
        precondition(InboxAdmission.allows(connected: true, enabledServer: "host", currentServer: "host", admittedServer: "host", paused: false, cancelled: false))
        precondition(!InboxAdmission.allows(connected: false, enabledServer: "host", currentServer: "host", admittedServer: "host", paused: false, cancelled: false))
        precondition(!InboxAdmission.allows(connected: true, enabledServer: "host", currentServer: "other", admittedServer: "host", paused: false, cancelled: false))
        precondition(!InboxAdmission.allows(connected: true, enabledServer: "", currentServer: "host", admittedServer: "host", paused: false, cancelled: false))
        precondition(!InboxAdmission.allows(connected: true, enabledServer: "host", currentServer: "host", admittedServer: "host", paused: true, cancelled: false))
        precondition(!InboxAdmission.allows(connected: true, enabledServer: "host", currentServer: "host", admittedServer: "host", paused: false, cancelled: true))
        print("PASS: inbox disconnect, server change, disabled, paused and cancellation block removal admission")
        precondition(AgentProbeResponse.isReady(Data(#"{"value":{"ready":true}}"#.utf8)))
        for value in [#"{"value":{"ready":false}}"#, #"{"ready":true}"#, #"{"value":{"ready":"true"}}"#, "invalid"] {
            precondition(!AgentProbeResponse.isReady(Data(value.utf8)))
        }
        print("PASS: local agent probe fails closed on malformed or non-ready responses")
        let capacity = StorageCapacity(totalBytes: 100_000_000_000, freeBytes: 25_000_000_000)
        precondition(capacity.usedPercent == 75 && capacity.freeGB == 25 && capacity.totalGB == 100)
        let searchURL = URLComponents(string: SessionSearch.path(query: "  Café & plano?  ", cursor: "opaque+/=&"))!
        let searchItems = Dictionary(uniqueKeysWithValues: searchURL.queryItems!.map { ($0.name, $0.value!) })
        precondition(searchItems["search"] == "Café & plano?")
        precondition(searchItems["cursor"] == "opaque+/=&" && searchItems["order"] == nil)
        precondition(SessionSearch.path(query: "hello").contains("order=desc"))
        print("PASS: server search query encoding and opaque cursor pagination")
        let sessionJSON = #"{"data":[{"id":"ses_123","title":"Example","location":{"directory":"/workspace"},"model":{"providerID":"example","id":"model"}}],"cursor":{"next":"older","previous":null}}"#
        let sessions = try decoder.decode(Page<Session>.self, from: Data(sessionJSON.utf8))
        precondition(sessions.data.first?.model?.id == "model")
        precondition(sessions.cursor?.next == "older")
        let messagesJSON = #"{"data":[{"id":"msg_1","type":"user","text":"Hello","time":{"created":1}},{"id":"msg_2","type":"assistant","content":[{"type":"text","text":"Hi"},{"type":"tool","name":"read","state":{"status":"completed","content":[{"type":"text","text":"OK"}]}}],"time":{"created":2,"completed":3}}],"cursor":{"next":null}}"#
        let messages = try decoder.decode(Page<Message>.self, from: Data(messagesJSON.utf8))
        precondition(messages.data.count == 2)
        precondition(messages.data[1].content?[1].state?.status == "completed")
        let permissionsJSON = #"{"data":[{"id":"per_1","action":"shell","resources":["pwd"]}]}"#
        let permissions = try decoder.decode(Page<Permission>.self, from: Data(permissionsJSON.utf8))
        precondition(permissions.data[0].action == "shell")
        for _ in 0..<100 { precondition(RequestID.message().hasPrefix("msg_")) }
        let failureJSON = #"{"id":"msg_failure","type":"assistant","content":[],"time":{"created":2,"completed":3},"error":{"type":"provider.auth","message":"Expired key"}}"#
        let failure = try decoder.decode(Message.self, from: Data(failureJSON.utf8))
        precondition(failure.error?.message == "Expired key")
        let text = PendingFile(name: "code.swift", mime: "text/plain", data: Data("print(1)".utf8))
        try PendingFile.validate([text])
        precondition(text.payload["uri"] as? String == "data:text/plain;base64,cHJpbnQoMSk=")
        precondition(text.category == "text")
        do {
            try PendingFile.validate(Array(repeating: text, count: 6))
            preconditionFailure("Attachment count limit missing")
        } catch { }
        do {
            try PendingFile.validate([PendingFile(name: "large", mime: "text/plain", data: Data(count: PendingFile.maxFileBytes + 1))])
            preconditionFailure("Attachment byte limit missing")
        } catch { }
        let ref = try decoder.decode(Session.Model.self, from: Data(#"{"id":"m","providerID":"p","variant":"high"}"#.utf8))
        precondition(ref.payload["variant"] as? String == "high")
        let catalog = try decoder.decode(Catalog.self, from: Data(#"{"models":[{"id":"m","providerID":"p","name":"Model","capabilities":{"input":["text","image"]},"variants":[{"id":"high"}],"status":"active"}],"agents":[{"id":"plan","name":"Plan"}]}"#.utf8))
        precondition(catalog.models[0].key == "p/m")
        precondition(catalog.agents[0].id == "plan")
        let control = try decoder.decode(ControlStatus.self, from: Data(#"{"configured":true,"enabled":false,"expiresAt":0,"sessionID":"ses_control","device":{"name":"Test","connected":true,"agentInstalled":true,"locked":null},"running":false,"pending":0,"activity":"Aguardando tarefa","ready":false}"#.utf8))
        precondition(!control.enabled && control.device.locked == nil)
        let json = try decoder.decode(JSONValue.self, from: Data(#"{"text":"Hello","enabled":true,"point":[12,34],"other":null}"#.utf8))
        precondition(json.pretty.contains("Hello") && json.pretty.contains("true"))
        let source = try decoder.decode(Permission.self, from: Data(#"{"id":"per_control","action":"iphone_mobile_launch_app","resources":["*"],"source":{"id":"call_control","messageID":"msg_control"}}"#.utf8))
        precondition(source.source?.id == "call_control")
        var reads = ReadState()
        let old = try decoder.decode(Session.self, from: Data(#"{"id":"ses_unread","location":{"directory":"/workspace"},"time":{"created":1,"updated":100,"idle":100},"outcome":"succeeded"}"#.utf8))
        let finished = try decoder.decode(Session.self, from: Data(#"{"id":"ses_unread","location":{"directory":"/workspace"},"time":{"created":1,"updated":200,"idle":200},"outcome":"succeeded"}"#.utf8))
        reads.initialize(server: "host", sessions: [old])
        precondition(!reads.isUnread(old, server: "host"))
        precondition(reads.isUnread(finished, server: "host"))
        reads.markRead(finished, server: "host")
        precondition(!reads.isUnread(finished, server: "host"))
        let restored = try decoder.decode(ReadState.self, from: JSONEncoder().encode(reads))
        precondition(!restored.isUnread(finished, server: "host"))
        precondition(restored.isUnread(finished, server: "different-host"))
        let running = try decoder.decode(Session.self, from: Data(#"{"id":"ses_running","location":{"directory":"/workspace"},"time":{"created":1,"updated":300}}"#.utf8))
        precondition(!reads.isUnread(running, server: "host"))
        let battery = try decoder.decode(HostStatus.self, from: Data(#"{"awake":true,"battery":{"available":true,"percentage":17,"charging":false,"onAC":false,"state":"Discharging"}}"#.utf8))
        precondition(battery.battery?.percentage == 17 && battery.battery?.onAC == false)
        let unavailable = try decoder.decode(HostStatus.self, from: Data(#"{"awake":true,"battery":{"available":false,"percentage":null,"charging":null,"onAC":null,"state":null}}"#.utf8))
        precondition(unavailable.battery?.percentage == nil)
        let question = try decoder.decode(QuestionForm.self, from: Data(#"{"id":"form_question","title":"Como seguir?","fields":[{"key":"confirm","type":"boolean","default":false},{"key":"answer","type":"string","required":true,"custom":true,"options":[{"value":"plan","label":"Planejar"}],"when":[{"key":"confirm","op":"eq","value":true}]}]}"#.utf8))
        precondition(question.fields[0].defaultValue == .bool(false))
        precondition(!question.visible(question.fields[1], answers: ["confirm": .bool(false)]))
        precondition(question.visible(question.fields[1], answers: ["confirm": .bool(true)]))
        precondition(question.fields[1].options?[0].value == "plan")
        precondition((JSONValue.array([.string("plan")]).object as? [String]) == ["plan"])
        let quota = try decoder.decode(CodexQuota.self, from: Data(#"{"available":true,"source":"Codex CLI","checkedAt":1000,"weekly":{"usedPercent":36,"windowMinutes":10080,"resetsAt":2000}}"#.utf8))
        precondition(quota.weekly?.remainingPercent == 64)
        var pins = PinState()
        pins.toggle("ses_first", server: "host")
        pins.toggle("ses_second", server: "host")
        precondition(pins.ids(server: "host") == ["ses_second", "ses_first"])
        precondition(!pins.contains("ses_first", server: "other"))
        pins.toggle("ses_second", server: "host")
        precondition(pins.ids(server: "host") == ["ses_first"])
        let restoredPins = try decoder.decode(PinState.self, from: JSONEncoder().encode(pins))
        precondition(restoredPins.contains("ses_first", server: "host"))
        let build = try decoder.decode(Session.self, from: Data(#"{"id":"ses_mode","agent":"build","title":"Before","location":{"directory":"/workspace"}}"#.utf8))
        let plan = try decoder.decode(Session.self, from: Data(#"{"id":"ses_mode","agent":"plan","title":"Before","location":{"directory":"/workspace"}}"#.utf8))
        let renamed = try decoder.decode(Session.self, from: Data(#"{"id":"ses_mode","agent":"build","title":"After","location":{"directory":"/workspace"}}"#.utf8))
        precondition(build != plan && build != renamed, "SwiftUI state must notice metadata changes for same session ID")
        print("PASS: native model decoding, pagination, tool status, permissions, message IDs")
        print("PASS: unread completion marker, read clearing, persistence, server isolation and running-session exclusion")
        print("PASS: model variants, catalog, attachment URIs/limits, provider errors")
    }
}
